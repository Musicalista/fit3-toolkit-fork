"""gen.py: writes the two generated headers hub.c includes, into a directory of your choice (never into the repository):

    icons.h      the 64 x 64 four-bit icons (the size of the stock app-list icons, 2,112 bytes each) of the apps (src/assets/mkicon.py draws them: our own artwork)
    gen_apps.h   HUB_MODE (0: one app owns the window, 1: a list of apps), HOST_MODE (1: each app is a window of its own, opened by the window manager with the stock slide), and the apps' sources included in the order of the list: APPS[] / NAPPS

Used by src/build_firmware.py and by the emulator tests (src/emu/mkimage.py)."""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, os.path.join(os.path.dirname(HERE), "assets"))
import mkicon

APPS = {"tennis": "app_tennis", "counter": "app_counter", "dice": "app_dice", "mars": "app_mars", "manager": "app_manager", "bench": "app_bench", "gameboy": "app_gameboy"}       # name -> the App symbol in src/watch/apps/<name>.c


def icons_h():
    out = ["/* generated by src/watch/gen.py: do not edit */", "#ifndef F3_ICONS_H", "#define F3_ICONS_H", '#include "ui.h"']
    for name in APPS:
        data = mkicon.encode_indexed4(*mkicon.draw(name, 64)); assert len(data) == 2112
        rows = ",\n".join("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) for i in range(0, len(data), 16))
        out.append("H const u8 ICON_%s_DATA[2112] = {\n%s\n};\nH const Icon ICON_%s = { ICON_HDR_I4(64, 64), 2112, ICON_%s_DATA, 0 };" % (name.upper(), rows, name.upper(), name.upper()))
    out.append("#endif")
    return "\n".join(out) + "\n"


def apps_h(apps, hub, install=False, host=False, reply=False):
    for a in apps:
        if a not in APPS: raise SystemExit("unknown app %r (available: %s)" % (a, ", ".join(APPS)))
    if not apps and not (hub and install): raise SystemExit("no apps")
    out = ["/* generated by src/watch/gen.py: do not edit */", "#define HUB_MODE %d" % (1 if hub else 0)]
    if install: out.append("#define F3X_LOADER 1")
    out.append("#define HOST_MODE %d" % (1 if hub and host else 0))
    if reply: out += ["#define REPLY_KBD 1", '#define KB_FONT_HEADER "kbfont.h"']
    out += ['#include "apps/%s.c"' % a for a in apps]
    out += ["static const App *const APPS[] = { %s };" % (", ".join("&" + APPS[a] for a in apps) or "0"), "#define NAPPS %d" % len(apps)]
    return "\n".join(out) + "\n"


def generate(apps, hub, outdir, install=False, host=False, kb_ttf=None, kb_langs=("en",), kb_emoji_ttf=None):
    """kb_ttf: a TTF with Latin glyphs (Roboto Medium): turns on the reply keyboard (kbd.c), its font and the layouts of kb_langs (kblang.py);
    kb_emoji_ttf: a monochrome emoji TTF (Noto Emoji): adds the emoji layer, its glyphs merged into the keyboard font at 22 px"""
    os.makedirs(outdir, exist_ok=True)
    if kb_ttf:
        import mkfont
        import kblang
        open(os.path.join(outdir, "kbfont.h"), "w").write(mkfont.emit(mkfont.build(kb_ttf, 24, kblang.alphabet(list(kb_langs)), polish=False, emoji_ttf=kb_emoji_ttf, emoji="".join(kblang.EMOJI) if kb_emoji_ttf else "", emoji_size=22), "KB"))
        open(os.path.join(outdir, "kblang.h"), "w").write(kblang.header(list(kb_langs), bool(kb_emoji_ttf)))
    open(os.path.join(outdir, "icons.h"), "w").write(icons_h()); open(os.path.join(outdir, "gen_apps.h"), "w").write(apps_h(apps, hub, install, host, bool(kb_ttf)))
    return outdir
