"""gen.py: writes the two generated headers hub.c includes, into a directory of your choice (never into the repository):

    icons.h      the 40 x 40 four-bit icons of the apps (src/assets/mkicon.py draws them: our own artwork)
    gen_apps.h   HUB_MODE (0: one app owns the window, 1: a list of apps), and the apps' sources included in the order of the list: APPS[] / NAPPS

Used by src/build_tennis.py and by the emulator tests (src/emu/mkimage.py)."""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, os.path.join(os.path.dirname(HERE), "assets"))
import mkicon

APPS = {"tennis": "app_tennis", "counter": "app_counter", "dice": "app_dice"}       # name -> the App symbol in src/watch/apps/<name>.c


def icons_h():
    out = ["/* generated by src/watch/gen.py: do not edit */", "#ifndef F3_ICONS_H", "#define F3_ICONS_H", '#include "ui.h"']
    for name in APPS:
        data = mkicon.encode_indexed4(*mkicon.draw(name, 40)); assert len(data) == 864
        rows = ",\n".join("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) for i in range(0, len(data), 16))
        out.append("H const u8 ICON_%s_DATA[864] = {\n%s\n};\nH const Icon ICON_%s = { ICON_HDR_I4(40, 40), 864, ICON_%s_DATA, 0 };" % (name.upper(), rows, name.upper(), name.upper()))
    out.append("#endif")
    return "\n".join(out) + "\n"


def apps_h(apps, hub):
    for a in apps:
        if a not in APPS: raise SystemExit("unknown app %r (available: %s)" % (a, ", ".join(APPS)))
    if not apps: raise SystemExit("no apps")
    out = ["/* generated by src/watch/gen.py: do not edit */", "#define HUB_MODE %d" % (1 if hub else 0)]
    out += ['#include "apps/%s.c"' % a for a in apps]
    out += ["static const App *const APPS[] = { %s };" % ", ".join("&" + APPS[a] for a in apps), "#define NAPPS (sizeof APPS / sizeof APPS[0])"]
    return "\n".join(out) + "\n"


def generate(apps, hub, outdir):
    os.makedirs(outdir, exist_ok=True)
    open(os.path.join(outdir, "icons.h"), "w").write(icons_h()); open(os.path.join(outdir, "gen_apps.h"), "w").write(apps_h(apps, hub))
    return outdir
